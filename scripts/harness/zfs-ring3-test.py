    # (B11, design k.126) the interrupt-latency probe: the per-CPU 100 Hz tick counters (sysinfo#35) around the close
    # that commits b11big.bin — a CPU that held interrupts off for the commit missed its ticks; the idle CPUs took theirs
    for _m in re.findall(r"zfsx: b11 close ticks( cpu0=\d+ cpu1=\d+ cpu2=\d+ cpu3=\d+)", out):
        _t = [int(x) for x in re.findall(r"=(\d+)", _m)]
